// Localstorage-ключ для вопроса, сохранённого при анонимной попытке отправки.
export const PENDING_KEY = 'askzakir:pendingQuestion';

export function readPending() {
  try { return localStorage.getItem(PENDING_KEY) || null; } catch { return null; }
}
export function writePending(text) {
  try { localStorage.setItem(PENDING_KEY, text); } catch {}
}
export function clearPending() {
  try { localStorage.removeItem(PENDING_KEY); } catch {}
}

